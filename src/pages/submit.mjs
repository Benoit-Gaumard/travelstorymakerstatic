    '<p>The best submissions tend to have one of these:</p>',
    '<ul>',
    '<li><strong>An unexpected kindness.</strong> The barman who let us sleep on beer crates in Reykjavík. The bus driver in Snowdonia who saw two head torches on the mountain and refused to leave.</li>',
    '<li><strong>A local rule you only learned by breaking it.</strong> The tissue packet on a Singapore hawker table. The bread that is never placed upside down in Uzbekistan.</li>',
    '<li><strong>A plan that fell apart and turned into the trip.</strong> Missed ferries, cancelled flights, four days stranded by a typhoon in a fishing village.</li>',
    '<li><strong>A small ritual done properly.</strong> Three glasses of tea in the Sahara. A monk\'s alms round at six in the morning. A market that closes at noon whatever you want.</li>',
    '<li><strong>A moment with no photograph.</strong> Usually the best ones.</li>',
    '</ul>',

    '<h2>What to include when you write</h2>',
    '<ul>',
