const EXAMPLE_WORDS = EXAMPLE.text.trim().split(/\s+/).length;
const EXAMPLE_PAGE = Math.ceil(EXAMPLE.id / 100);
const EXAMPLE_HREF = (EXAMPLE_PAGE === 1 ? '/travelstories/' : '/travelstories/page/' + EXAMPLE_PAGE + '/') + '#e' + EXAMPLE.id;

